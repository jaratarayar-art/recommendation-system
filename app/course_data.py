# 6. ตรวจสอบตารางเรียนชน

# ============================================================

def class_conflict(

    elective,

    mandatory

):

    for (

        e_day,

        e_start,

        e_end

    ) in elective["classes"]:

        for (

            m_day,

            m_start,

            m_end

        ) in mandatory["classes"]:

            if e_day == m_day:

                if time_overlap(

                    e_start,

                    e_end,

                    m_start,

                    m_end

                ):

                    return True

    return False


