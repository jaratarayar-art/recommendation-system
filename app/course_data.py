# 7. ตรวจสอบการสอบชน

# ============================================================

def exam_conflict(

    elective_exam,

    mandatory_exam

):

    # กรณีไม่มีสอบ

    if elective_exam is None:

        return False

    if mandatory_exam is None:

        return False


    e_date, e_start, e_end = elective_exam

    m_date, m_start, m_end = mandatory_exam


    # คนละวัน ไม่ชน

    if e_date != m_date:

        return False


    return time_overlap(

        e_start,

        e_end,

        m_start,

        m_end

    )