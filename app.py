# ============================================================
# ฟังก์ชันแปลงเวลา "HH:MM" -> จำนวนนาที (เหมือนโค้ดเดิม)
# ============================================================
def time_to_minutes(time_string):
    hour, minute = map(int, time_string.split(":"))
    return hour * 60 + minute


# ============================================================
# ตรวจสอบว่าช่วงเวลาสองช่วงทับกันหรือไม่ (เหมือนโค้ดเดิม)
# ============================================================
def time_overlap(start1, end1, start2, end2):
    start1 = time_to_minutes(start1)
    end1 = time_to_minutes(end1)
    start2 = time_to_minutes(start2)
    end2 = time_to_minutes(end2)
    return start1 < end2 and start2 < end1


# ============================================================
# ตรวจสอบว่าตารางเรียนของวิชาเสรีชนกับวิชาบังคับหรือไม่ (เหมือนโค้ดเดิม)
# ============================================================
def class_conflict(elective, mandatory):
    for e_day, e_start, e_end in elective["classes"]:
        for m_day, m_start, m_end in mandatory["classes"]:
            if e_day == m_day:
                if time_overlap(e_start, e_end, m_start, m_end):
                    return True
    return False


# ============================================================
# ตรวจสอบว่าวันสอบชนกันหรือไม่ (เหมือนโค้ดเดิม)
# ============================================================
def exam_conflict(elective_exam, mandatory_exam):
    if elective_exam is None:
        return False
    if mandatory_exam is None:
        return False

    e_date, e_start, e_end = elective_exam
    m_date, m_start, m_end = mandatory_exam

    if e_date != m_date:
        return False

    return time_overlap(e_start, e_end, m_start, m_end)


# ============================================================
# ฟังก์ชัน Normalize คะแนนให้อยู่ในช่วง 0-1 (เหมือนโค้ดเดิม)
# ============================================================
def normalize(series):
    min_value = series.min()
    max_value = series.max()

    if max_value == min_value:
        return pd.Series(np.zeros(len(series)), index=series.index)

    return (series - min_value) / (max_value - min_value)


